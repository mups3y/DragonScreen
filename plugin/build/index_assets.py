#!/usr/bin/env python
"""
Regenerate docs/ASSET_INDEX.md - one line per asset we own.

WHY THIS EXISTS: on 2026-08-05 I declared "there is no Dragon illustration" and was about to build
one. It was embedded in Container.svg the whole time. Answering "do we have X?" must cost one grep,
not a search of three folders and two zips.

Run after adding any asset:  python plugin/build/index_assets.py
"""
import os, struct, glob
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT  = os.path.join(ROOT, 'docs', 'ASSET_INDEX.md')

def png_size(p):
    try:
        d = open(p, 'rb').read(24)
        if d[1:4] != b'PNG': return ''
        w, h = struct.unpack('>II', d[16:24]); return '%dx%d' % (w, h)
    except Exception: return ''

SECTIONS = [
    ('SHIPPED - these go into the game', 'plugin/GameData/DragonScreen/art', '*'),
    ('Reference art rendered from the Figma SVGs', 'plugin/build/refart', '*.png'),
    ('EMBEDDED artwork extracted from inside those SVGs', 'plugin/build/refart/embedded', '*'),
    ('Vue recreation assets (Apache-2.0)', 'assets/reference/dragon2-ui-assets/docs/img', '*'),
    ('Vue recreation, top level', 'assets/reference/dragon2-ui-assets/docs', '*.png'),
    ('Fonts', 'assets/d-din', '*.ttf'),
    ('Source SVGs', 'assets/figma', '*/*.svg'),
]

lines = ['# Asset index — everything we own, one line each', '',
         'GENERATED by `plugin/build/index_assets.py`. Re-run it after adding an asset.', '',
         '**Before concluding an asset does not exist, grep this file.** And remember the SVGs are',
         'mostly embedded rasters — `rasterise_all.py` renders the vectors and drops the images;',
         '`extract_embedded.py` pulls the images out. Either alone is misleading.', '']

for title, rel, pat in SECTIONS:
    d = os.path.join(ROOT, rel)
    found = sorted(glob.glob(os.path.join(d, pat)))
    lines.append('## %s' % title)
    lines.append('')
    lines.append('`%s`' % rel)
    lines.append('')
    if not found:
        lines.append('_(nothing here)_'); lines.append(''); continue
    for f in found:
        if os.path.isdir(f): continue
        kb = os.path.getsize(f) / 1024.0
        sz = png_size(f)
        lines.append('- `%s` %s %s' % (os.path.relpath(f, d).replace(os.sep, chr(47)),
                                       ('— ' + sz) if sz else '', '(%.0f KB)' % kb))
    lines.append('')

open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
print('wrote %s (%d lines)' % (OUT, len(lines)))
