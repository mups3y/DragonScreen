#!/usr/bin/env python
"""
Extract the reference UI's ACTUAL layout from its source, into docs/UI_AUDIT.md.

    python plugin/build/audit_ui.py

---- WHY THIS EXISTS ----
Every page in this project that was built from a *rendered picture* of the reference came out wrong
in a way that took a game restart to notice. DOCKING was the worst: it was designed from
`Frame 58.svg`, a static Figma export, plus notes written while looking at the live demo - when the
demo's own source was sitting on disk with the exact coordinates in it.

A rendered SVG loses the semantics. A screenshot loses them too, and adds a perspective error. The
Vue source has `#navball { left: 14.59%; bottom: 8%; }` written down. Read that instead.

So this is the same idea as `index_assets.py`: turn a question that keeps being answered from memory
into a file that is generated from ground truth and can be grepped.

---- WHAT IT READS ----
    assets/reference/dragon2-ui-master/src/views/*.vue        the five pages
    assets/reference/dragon2-ui-master/src/components/*.vue   the panels they compose
    assets/reference/dashboard-ui-figma/*.svg                 the Figma frames (text + position)

Re-run it after re-extracting either zip.
"""
import os, re, io, glob

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
VUE = os.path.join(ROOT, 'assets', 'reference', 'dragon2-ui-master', 'src')
FIGMA = os.path.join(ROOT, 'assets', 'reference', 'dashboard-ui-figma')
OUT = os.path.join(ROOT, 'docs', 'UI_AUDIT.md')

POS_KEYS = ('top', 'left', 'right', 'bottom', 'width', 'height', 'transform')


def read(p):
    return io.open(p, encoding='utf-8', errors='replace').read()


def template_of(src):
    i = src.find('<template')
    j = src.rfind('</template>')
    return src[i:j] if (i >= 0 and j > i) else ''


def style_of(src):
    i = src.rfind('<style')
    return src[i:] if i >= 0 else ''


def positioned(style):
    """Selectors that place something, with the properties that place it."""
    out = []
    for sel, body in re.findall(r'([#.][A-Za-z0-9_\-, .#:>\s]+)\{([^}]*)\}', style):
        sel = ' '.join(sel.split())
        props = {}
        for line in body.split(';'):
            if ':' not in line:
                continue
            k, v = line.split(':', 1)
            k = k.strip()
            if k in POS_KEYS:
                props[k] = ' '.join(v.split())
        if not props:
            continue
        if not any(k in props for k in ('top', 'left', 'right', 'bottom')):
            continue
        out.append((sel, props))
    return out


def labels(tpl):
    """Visible text, with the svg path soup removed."""
    t = re.sub(r'<path[^>]*>', '', tpl)
    t = re.sub(r'<svg[^>]*>', ' ', t)
    t = re.sub(r'\s+', ' ', t)
    found = re.findall(r'>([^<>{}]{2,44})<', t)
    seen, out = set(), []
    for f in found:
        f = f.strip()
        if not f or f.lower() in seen:
            continue
        if not re.search(r'[A-Za-z]', f):
            continue
        seen.add(f.lower())
        out.append(f)
    return out


def assets(src):
    a = set()
    for m in re.findall(r"require\(['\"]([^'\"]+)['\"]\)", src):
        a.add(os.path.basename(m))
    for m in re.findall(r"""src=['"]([^'"]+)['"]""", src):
        a.add(os.path.basename(m))
    for m in re.findall(r"url\(['\"]?([^'\")]+)", src):
        a.add(os.path.basename(m))
    for m in re.findall(r"""load\(['"]([^'"]+\.(?:glb|png|jpg))['"]""", src):
        a.add(os.path.basename(m))
    return sorted(x for x in a if '.' in x)


def routes():
    p = os.path.join(VUE, 'router', 'index.js')
    if not os.path.isfile(p):
        return []
    s = read(p)
    return re.findall(r"path:\s*'([^']+)',\s*name:\s*'([^']+)'", s)


def figma_text(path):
    """Text nodes with their placement, so a frame's labels are addressable."""
    s = read(path)
    out = []
    for m in re.finditer(r'<text[^>]*?(?:x="([-\d.]+)")?[^>]*?(?:y="([-\d.]+)")?[^>]*>(.*?)</text>',
                         s, re.S):
        x, y, body = m.group(1), m.group(2), m.group(3)
        txt = ' '.join(re.sub(r'<[^>]+>', '', body).split())
        if txt:
            out.append((x or '?', y or '?', txt[:44]))
    return out


def main():
    if not os.path.isdir(VUE):
        raise SystemExit('missing %s - extract the zip first' % VUE)

    L = []
    w = L.append
    w('# UI AUDIT — the reference UI as its SOURCE describes it')
    w('')
    w('**GENERATED by `plugin/build/audit_ui.py`. Do not hand-edit.**')
    w('')
    w('Every page built from a *rendered picture* of the reference came out wrong in a way that cost')
    w('a game restart. The Vue source states its layout exactly — `#navball { left: 14.59%; bottom:')
    w('8% }` — so read that, not a screenshot. Grep this file before designing any page.')
    w('')

    r = routes()
    if r:
        w('## Routes')
        w('')
        w('| path | view |')
        w('|---|---|')
        for path, name in r:
            w('| `%s` | %s |' % (path, name))
        w('')

    for kind, pattern in (('View', 'views/*.vue'), ('Component', 'components/*.vue')):
        for f in sorted(glob.glob(os.path.join(VUE, pattern))):
            src = read(f)
            name = os.path.basename(f)
            pos = positioned(style_of(src))
            lab = labels(template_of(src))
            ass = assets(src)

            w('## %s — %s' % (kind, name))
            w('')
            w('%d lines. ' % len(src.splitlines()) +
              ('Assets: %s' % ', '.join('`%s`' % a for a in ass) if ass else 'No assets.'))
            w('')
            if pos:
                w('| selector | placement |')
                w('|---|---|')
                for sel, props in pos:
                    place = ' '.join('%s:%s' % (k, props[k]) for k in POS_KEYS if k in props)
                    w('| `%s` | %s |' % (sel[:44], place))
                w('')
            if lab:
                w('Labels: ' + ', '.join('`%s`' % x for x in lab[:40]))
                w('')

    figs = sorted(glob.glob(os.path.join(FIGMA, '*.svg')))
    if figs:
        w('## Figma frames — text nodes with placement')
        w('')
        for f in figs:
            t = figma_text(f)
            w('### %s' % os.path.basename(f))
            w('')
            if not t:
                w('_No live text nodes — this frame is an embedded raster. '
                  'See `build/refart/embedded/`._')
                w('')
                continue
            w('| x | y | text |')
            w('|---|---|---|')
            for x, y, txt in t[:60]:
                w('| %s | %s | %s |' % (x, y, txt.replace('|', '\\|')))
            if len(t) > 60:
                w('')
                w('_...%d more text nodes._' % (len(t) - 60))
            w('')

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
    print('wrote %s  (%.1f KB)' % (OUT, os.path.getsize(OUT) / 1024.0))


if __name__ == '__main__':
    main()
